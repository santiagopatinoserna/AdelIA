class EvidenceChunk(Base):
    __tablename__ = "evidence_chunks"
    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    source_id = Column(
        UUID(as_uuid=True),
        ForeignKey("evidence_sources.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    content = Column(Text, nullable=False)
    chunk_index = Column(Integer, nullable=False)
    chunk_metadata = Column(JSONB)
    embedding = Column(Vector(1024))
    created_at = Column(DateTime(timezone=True), server_default=func.now(), nullable=False)
    # The owning source's language, copied here because a generated column
    # cannot read another table and `tsv` is generated from it (migration
    # 0021). The loader writes it with the chunk; tests/test_hybrid_retrieval.py
    # fails if any row disagrees with its source.
    language = Column(String(8), nullable=False, server_default=text("'en'"))
    # Full-text vector for hybrid retrieval, in the row's own language
    # (spanish / french / english, `simple` for anything else). Generated by
    # Postgres, never written by the app, deferred like Chunk.tsv.
    tsv = deferred(Column(TSVECTOR, Computed(
        "CASE language "
        "WHEN 'es' THEN to_tsvector('spanish'::regconfig, content) "
        "WHEN 'fr' THEN to_tsvector('french'::regconfig, content) "
        "WHEN 'en' THEN to_tsvector('english'::regconfig, content) "
        "ELSE to_tsvector('simple'::regconfig, content) END",
        persisted=True,
    )))

    __table_args__ = (Index("ix_evidence_chunks_tsv", "tsv", postgresql_using="gin"),)


